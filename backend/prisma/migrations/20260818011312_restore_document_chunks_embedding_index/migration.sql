-- Restores the ivfflat index on document_chunks.embedding, which the
-- previous migration (20260818011124_add_user_name_and_must_reset_password)
-- accidentally dropped. That index was originally added by hand to the
-- initial migration (see D-020/D-021 in DECISIONS.md) because it isn't
-- expressible through Prisma's schema DSL — Prisma's diff engine has no
-- way to know it should exist, so any subsequent `prisma migrate dev` sees
-- it as drift and drops it to "reconcile" the schema. This migration exists
-- so the recorded history matches what the database should actually look
-- like; it was NOT generated by `prisma migrate dev` (that command wants to
-- reset the whole database when it encounters this same drift) — it was
-- written by hand and applied via `prisma migrate resolve --applied`,
-- since the CREATE INDEX below was already run manually against the
-- live database before this file existed.
--
-- Anyone touching document_chunks/embedding in the future: expect this to
-- happen again on the next `prisma migrate dev` unless a better long-term
-- fix is adopted (e.g. an Unsupported-type-aware migration workflow, or
-- moving vector-index management out of Prisma's migration history
-- entirely).
CREATE INDEX IF NOT EXISTS document_chunks_embedding_idx ON document_chunks
USING ivfflat (embedding vector_cosine_ops) WITH (lists = 100);
